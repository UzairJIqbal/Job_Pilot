-- Discovery: ATS company boards, board-sourced jobs, and search preferences.
--
-- companies is shared reference data: every signed-in user can read it, nobody
-- writes it through the API. Seeded with public Greenhouse, Lever and Ashby
-- boards that returned open jobs on 2026-10-17.

-- ---------------------------------------------------------------------------
-- companies: one row per public ATS job board
-- ---------------------------------------------------------------------------
CREATE TABLE public.companies (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name        text NOT NULL,
  ats         text NOT NULL CHECK (ats IN ('greenhouse', 'lever', 'ashby')),
  board_token text NOT NULL CHECK (board_token ~ '^[A-Za-z0-9._-]+$'),
  active      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (ats, board_token)
);

CREATE INDEX companies_active_idx ON public.companies (active, ats);

REVOKE ALL ON public.companies FROM anon, authenticated;
GRANT SELECT ON public.companies TO authenticated;

ALTER TABLE public.companies ENABLE ROW LEVEL SECURITY;

CREATE POLICY companies_select ON public.companies FOR SELECT TO authenticated
  USING (true);

-- ---------------------------------------------------------------------------
-- jobs: board-sourced listings
-- ---------------------------------------------------------------------------
ALTER TABLE public.jobs DROP CONSTRAINT jobs_source_check;
ALTER TABLE public.jobs ADD CONSTRAINT jobs_source_check
  CHECK (source IN ('search', 'url', 'board'));

ALTER TABLE public.jobs
  ADD COLUMN ats        text CHECK (ats IS NULL OR ats IN ('greenhouse', 'lever', 'ashby')),
  ADD COLUMN ats_job_id text,
  ADD COLUMN posted_at  timestamptz,
  ADD COLUMN fit_reason text,
  ADD CONSTRAINT jobs_ats_pair CHECK ((ats IS NULL) = (ats_job_id IS NULL));

-- One copy of an ATS posting per user, however it was found.
CREATE UNIQUE INDEX jobs_user_ats_job_uidx
  ON public.jobs (user_id, ats, ats_job_id)
  WHERE ats_job_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- profiles: hard filters applied before AI scoring
-- ---------------------------------------------------------------------------
ALTER TABLE public.profiles
  ADD COLUMN salary_min         integer CHECK (salary_min IS NULL OR salary_min >= 0),
  ADD COLUMN seniority          text[] NOT NULL DEFAULT '{}',
  ADD COLUMN excluded_companies text[] NOT NULL DEFAULT '{}',
  ADD COLUMN excluded_keywords  text[] NOT NULL DEFAULT '{}',
  ADD COLUMN auto_discover      boolean NOT NULL DEFAULT false,
  ADD COLUMN last_discovered_at timestamptz;

